// Recebe a média dos traços [smile, eyes, brow, jaw, round] e devolve o Pokémon mais parecido
export function bestMatch(me) {
  const dist = p => p[2].reduce((s, v, i) => s + (v - me[i]) ** 2, 0);
  const best = [...POKEMON].sort((a, b) => dist(a) - dist(b))[0];
  const match = Math.round(100 * (1 - Math.sqrt(dist(best) / TRAITS.length)));
  return { id: best[0], name: best[1], why: best[3], match };
}
